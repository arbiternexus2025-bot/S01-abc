from __future__ import annotations
import numpy as np
from dataclasses import dataclass, field
from typing import List, Optional, Dict, Any, Tuple


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass
class HTFWindow:
    """One directional bias period generated by the Higher TF."""
    direction: int          # +1 long, -1 short
    sig_bar: int            # HTF bar index of the flip
    sig_price: float        # HTF close of the signal bar
    sig_atr: float          # HTF ATR at signal
    start_time: Any         # datetime of window start (next HTF bar)
    end_time: Any           # datetime of window end (opposite flip)
    limit_price: float      # pre-computed limit level


@dataclass
class S43Signal:
    """One filled M1 limit entry."""
    direction: int
    entry_bar: int          # M1 bar index of fill
    entry_price: float      # limit fill price
    stop: float             # initial M1 PSAR stop (prev-bar)
    limit_price: float
    htf_mode: str           # "M5_LIM070" | "M30_LIM050" | "H1_LIM040"
    htf_sig_price: float
    htf_atr: float
    limit_off: float
    grade: str = ""

    def as_dict(self) -> Dict[str, Any]:
        return {
            "direction": self.direction,
            "entry_bar": self.entry_bar,
            "entry_price": self.entry_price,
            "stop": self.stop,
            "limit_price": self.limit_price,
            "htf_mode": self.htf_mode,
            "htf_sig_price": self.htf_sig_price,
            "htf_atr": self.htf_atr,
            "limit_off": self.limit_off,
            "grade": self.grade,
        }


# ---------------------------------------------------------------------------
# Indicator helpers
# ---------------------------------------------------------------------------

def _ema(c: np.ndarray, period: int = 9) -> np.ndarray:
    return pd_ewm(c, period)


def pd_ewm(arr: np.ndarray, span: int) -> np.ndarray:
    """Pure-numpy EMA (equivalent to pandas ewm span)."""
    alpha = 2.0 / (span + 1.0)
    out = np.empty_like(arr, dtype=float)
    out[0] = arr[0]
    for i in range(1, len(arr)):
        out[i] = alpha * arr[i] + (1.0 - alpha) * out[i - 1]
    return out


def _atr(h: np.ndarray, l: np.ndarray, c: np.ndarray, n: int = 14) -> np.ndarray:
    tr = np.maximum(h - l,
                    np.maximum(np.abs(h - np.roll(c, 1)),
                               np.abs(l - np.roll(c, 1))))
    tr[0] = h[0] - l[0]
    return pd_ewm(tr, n)   # Wilder-style via EMA approximation


def _psar(h: np.ndarray, l: np.ndarray,
          af0: float = 0.02, step: float = 0.02, afm: float = 0.2
          ) -> Tuple[np.ndarray, np.ndarray]:
    n = len(h)
    sar = np.empty(n)
    trend = np.empty(n, dtype=np.int8)
    ep = np.empty(n)
    af = np.empty(n)
    sar[0], trend[0], ep[0], af[0] = l[0], 1, h[0], af0
    for i in range(1, n):
        ps, pt, pe, pa = sar[i - 1], trend[i - 1], ep[i - 1], af[i - 1]
        if pt == 1:
            s = min(ps + pa * (pe - ps), l[i - 1],
                    l[i - 2] if i >= 2 else l[i - 1])
            if l[i] < s:
                trend[i], sar[i], ep[i], af[i] = -1, pe, l[i], af0
            else:
                trend[i] = 1
                if h[i] > pe:
                    ep[i], af[i] = h[i], min(pa + step, afm)
                else:
                    ep[i], af[i] = pe, pa
                sar[i] = s
        else:
            s = max(ps + pa * (pe - ps), h[i - 1],
                    h[i - 2] if i >= 2 else h[i - 1])
            if h[i] > s:
                trend[i], sar[i], ep[i], af[i] = 1, pe, h[i], af0
            else:
                trend[i] = -1
                if l[i] < pe:
                    ep[i], af[i] = l[i], min(pa + step, afm)
                else:
                    ep[i], af[i] = pe, pa
                sar[i] = s
    return sar, trend


def _atr_pct(atr_arr: np.ndarray, window: int = 400, min_p: int = 80) -> np.ndarray:
    """Rolling percentile-style volatility score via MAD z-score → sigmoid."""
    n = len(atr_arr)
    out = np.full(n, np.nan)
    for i in range(min_p - 1, n):
        start = max(0, i - window + 1)
        seg = atr_arr[start:i + 1]
        med = np.median(seg)
        mad = np.median(np.abs(seg - med))
        z = (atr_arr[i] - med) / (mad * 1.4826 + 1e-12)
        out[i] = 1.0 / (1.0 + np.exp(-1.7 * z))
    return out


