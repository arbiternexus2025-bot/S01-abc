# Core detector
# ---------------------------------------------------------------------------

class S43Detector:
    """
    Detects the three locked HTF→M1 Limit setups on XAUUSD.

    Parameters
    ----------
    mode : str
        "A" | "B" | "C" | "ALL"
        A = M5  NOVOL_NOEMA LIMIT 0.70
        B = M30 VOL40_EMA   LIMIT 0.50
        C = H1  VOL40_EMA   LIMIT 0.40
        ALL = run all three (signals tagged by htf_mode)

    max_wait_m1 : int
        Maximum M1 bars after window start to wait for limit fill (default 180).
    """

    MODES = {
        "A": dict(htf="M5",  min_pct=0.0,  use_ema=False, limit_off=0.70,
                  label="M5_LIM070",  grade="B+"),
        "B": dict(htf="M30", min_pct=0.40, use_ema=True,  limit_off=0.50,
                  label="M30_LIM050", grade="A"),
        "C": dict(htf="H1",  min_pct=0.40, use_ema=True,  limit_off=0.40,
                  label="H1_LIM040",  grade="A"),
    }

    def __init__(self, mode: str = "ALL", max_wait_m1: int = 180):
        mode = mode.upper()
        if mode not in ("A", "B", "C", "ALL"):
            raise ValueError("mode must be A, B, C or ALL")
        self.mode = mode
        self.max_wait = max_wait_m1

    # ------------------------------------------------------------------
    def _prepare(self, o, h, l, c):
        sar, trend = _psar(h, l)
        e9 = pd_ewm(c, 9)
        a = _atr(h, l, c, 14)
        ap = _atr_pct(a)
        prev = np.roll(trend, 1)
        prev[0] = trend[0]
        flipL = ((prev == -1) & (trend == 1)).astype(np.int8)
        flipS = ((prev == 1) & (trend == -1)).astype(np.int8)
        return dict(o=o, h=h, l=l, c=c, sar=sar, trend=trend,
                    e9=e9, atr=a, atr_pct=ap, flipL=flipL, flipS=flipS)

    # ------------------------------------------------------------------
    def _build_windows(self, htf: dict, times: np.ndarray,
                       min_pct: float, use_ema: bool,
                       limit_off: float) -> List[HTFWindow]:
        n = len(htf["c"])
        windows = []
        i = 20
        while i < n - 1:
            long = htf["flipL"][i] == 1
            short = htf["flipS"][i] == 1
            if use_ema:
                long = (long and htf["e9"][i] > htf["e9"][i - 1]
                        and htf["c"][i] > htf["e9"][i])
                short = (short and htf["e9"][i] < htf["e9"][i - 1]
                         and htf["c"][i] < htf["e9"][i])
            if min_pct > 0:
                if np.isnan(htf["atr_pct"][i]) or htf["atr_pct"][i] < min_pct:
                    long = short = False
            if not (long or short):
                i += 1
                continue

            direction = 1 if long else -1
            start_i = i + 1
            end_i = n - 1
            for j in range(start_i, n):
                if direction == 1 and htf["flipS"][j] == 1:
                    end_i = j
                    break
                if direction == -1 and htf["flipL"][j] == 1:
                    end_i = j
                    break

            atr_val = htf["atr"][i] if not np.isnan(htf["atr"][i]) else 1.0
            sig_price = htf["c"][i]
            # Limit relative to HTF signal close
            limit_price = sig_price - direction * limit_off * atr_val

            windows.append(HTFWindow(
                direction=direction,
                sig_bar=i,
                sig_price=sig_price,
                sig_atr=atr_val,
                start_time=times[start_i] if start_i < n else times[i],
                end_time=times[end_i],
                limit_price=limit_price,
            ))
            i = end_i + 1
        return windows

    # ------------------------------------------------------------------
    def _scan_m1_fills(self, windows: List[HTFWindow],
                       m1: dict, m1_times: np.ndarray,
                       label: str, grade: str, limit_off: float
                       ) -> List[S43Signal]:
        signals = []
        n = len(m1["c"])
        for w in windows:
            # M1 bars that fall inside the HTF window
            mask = (m1_times >= np.datetime64(w.start_time)) & \
                   (m1_times <= np.datetime64(w.end_time))
            idxs = np.where(mask)[0]
            if len(idxs) == 0:
                continue
            si = int(idxs[0])
            ei_max = int(idxs[-1])

            filled = False
            for k, i in enumerate(range(si, ei_max + 1)):
                if k > self.max_wait:
                    break
                # Does this M1 bar touch the limit?
                if m1["l"][i] <= w.limit_price <= m1["h"][i]:
                    # Initial stop = previous-bar PSAR
                    stop = m1["sar"][i - 1] if i > 0 else m1["sar"][i]
                    signals.append(S43Signal(
                        direction=w.direction,
                        entry_bar=i,
                        entry_price=w.limit_price,
                        stop=stop,
                        limit_price=w.limit_price,
                        htf_mode=label,
                        htf_sig_price=w.sig_price,
                        htf_atr=w.sig_atr,
                        limit_off=limit_off,
                        grade=grade,
                    ))
                    filled = True
                    break
            # max_entries = 1 already enforced by break
        return signals

    # ------------------------------------------------------------------
    def detect(self,
               htf_data: Dict[str, np.ndarray],
               m1_data: Dict[str, np.ndarray],
               htf_times: np.ndarray,
               m1_times: np.ndarray,
               mode: Optional[str] = None,
               ) -> List[S43Signal]:
        """
        Run detection.

        Parameters
        ----------
        htf_data : dict with keys Open, High, Low, Close (numpy arrays)
                   Must match the HTF of the requested mode(s).
                   When mode="ALL" you must call detect three times
                   (once per HTF) or use detect_all().
        m1_data  : same structure for M1 bars
        htf_times, m1_times : datetime64 arrays aligned with the bars

        Returns
        -------
        List[S43Signal]
        """
        mode = (mode or self.mode).upper()
        if mode == "ALL":
            raise ValueError("Use detect_all() when mode=ALL, or pass mode=A/B/C")

        cfg = self.MODES[mode]
        htf = self._prepare(htf_data["Open"], htf_data["High"],
                            htf_data["Low"], htf_data["Close"])
        m1 = self._prepare(m1_data["Open"], m1_data["High"],
                           m1_data["Low"], m1_data["Close"])

        windows = self._build_windows(
            htf, htf_times,
            min_pct=cfg["min_pct"],
            use_ema=cfg["use_ema"],
            limit_off=cfg["limit_off"],
        )
        return self._scan_m1_fills(
            windows, m1, m1_times,
            label=cfg["label"],
            grade=cfg["grade"],
            limit_off=cfg["limit_off"],
        )

    def detect_all(self,
                   data: Dict[str, Dict[str, np.ndarray]],
                   times: Dict[str, np.ndarray],
                   ) -> List[S43Signal]:
        """
        Convenience: run all three locked modes.

        data  = {"M5": {...}, "M30": {...}, "H1": {...}, "M1": {...}}
        times = {"M5": ..., "M30": ..., "H1": ..., "M1": ...}
        """
        all_sigs = []
        for m in ("A", "B", "C"):
            cfg = self.MODES[m]
            htf_key = cfg["htf"]
            sigs = self.detect(
                htf_data=data[htf_key],
                m1_data=data["M1"],
                htf_times=times[htf_key],
                m1_times=times["M1"],
                mode=m,
            )
            all_sigs.extend(sigs)
        # sort by entry bar
        all_sigs.sort(key=lambda s: s.entry_bar)
        return all_sigs


